#!/usr/bin/env node
/**
 * Writes `<pkgDir>/src/version.ts` from `<pkgDir>/package.json`, so CLIs and
 * `packageInfo` report the manifest's real name and version instead of a
 * hard-coded literal. Runs at the start of each package's `build`; the output is
 * committed so `typecheck` and `test` work without a build. `scripts/smoke.mjs`
 * fails when a bin's `--version` disagrees with its manifest.
 *
 * Usage (from a package dir): node ../scripts/gen-version.mjs <pkgDir>   (pkgDir defaults to cwd)
 * Idempotent: the file is rewritten only when its content changes.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const pkgDir = resolve(process.argv[2] ?? process.cwd());
const { name, version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

const target = join(pkgDir, 'src', 'version.ts');
const content = `// Generated by scripts/gen-version.mjs from package.json — do not edit.
export const PACKAGE_NAME = '${name}';
export const VERSION = '${version}';
`;

if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
  writeFileSync(target, content);
}
